// Saved data version 17: "Machine" now means a pin-loaded stack; plate-loaded and
// Smith machines are their own equipment. Only an exercise still marked plain
// "machine" is changed.
const MACHINE_KINDS = {
  "plate-loaded": ["hack-squat", "leg-press", "leg-press-calf-raise", "chest-supported-t-bar-row", "chest-supported-high-row-machine"],
  "smith-machine": ["smith-squat", "smith-hip-thrust", "smith-romanian-deadlift"],
};

export function applyMachineKinds(state) {
  for (const [kind, ids] of Object.entries(MACHINE_KINDS)) {
    for (const exercise of state.exercises) {
      if (ids.includes(exercise.id) && exercise.equipment.includes("machine")) exercise.equipment = exercise.equipment.map((id) => (id === "machine" ? kind : id));
    }
  }
}

export function applyLibraryUpdate(state, update = LIBRARY_UPDATE) {
  const byId = (id) => state.exercises.find((exercise) => exercise.id === id);
  const taken = (except) => new Set(state.exercises.filter((exercise) => exercise !== except).flatMap((exercise) => [exercise.name, ...exercise.aliases]).map(normalizedName));
  for (const [id, from, to] of update.renames) {
    const exercise = byId(id);
    if (!exercise || exercise.name !== from || taken(exercise).has(normalizedName(to))) continue;
    exercise.aliases = exercise.aliases.filter((alias) => normalizedName(alias) !== normalizedName(to));
    if (!update.forget?.includes(from) && normalizedName(from) !== normalizedName(to) && !exercise.aliases.some((alias) => normalizedName(alias) === normalizedName(from))) exercise.aliases.push(from);
    exercise.name = to;
  }
  for (const exercise of update.added) {
    const names = taken();
    if (byId(exercise.id) || [exercise.name, ...exercise.aliases].some((name) => names.has(normalizedName(name)))) continue;
    state.exercises.push(structuredClone(exercise));
  }
  for (const [a, b, relation] of update.links) {
    const first = byId(a);
    const second = byId(b);
    if (!first || !second || first.relatedExercises.some((related) => related.exerciseId === b)) continue;
    first.relatedExercises.push({ exerciseId: b, relation });
    second.relatedExercises.push({ exerciseId: a, relation: INVERSE[relation] });
  }
}
